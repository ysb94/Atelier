import assert from 'node:assert/strict'

export async function verifyAnniversaryLeave({db,actor,value,create,peer,ops,company}) {
  await db.exec('reset role;alter table employee_roster add column resigned_on date')
  const cycle = async (hire, day) => (await db.query('select starts_on::text,ends_on::text,grant_days::float from app.employee_leave_cycle($1,$2)',[hire,day])).rows[0]
  assert.deepEqual(await cycle('2025-11-03','2026-11-03'),{starts_on:'2025-11-03',ends_on:'2026-11-03',grant_days:11})
  assert.deepEqual(await cycle('2025-11-03','2026-11-04'),{starts_on:'2026-11-04',ends_on:'2027-11-03',grant_days:15})
  assert.equal((await cycle('2024-02-29','2027-03-01')).grant_days,16)
  assert.equal((await cycle('2000-01-01','2026-01-02')).grant_days,25)
  assert.equal((await cycle('2026-03-30','2026-10-30')).grant_days,6)
  assert.equal((await cycle('2026-03-30','2026-10-31')).grant_days,7)
  assert.equal(await cycle('2027-01-01','2026-10-29'),undefined)
  await db.query('update profiles set hire_date=$1 where id=$2',['2024-11-03',peer])
  await actor(ops)
  await db.query('update employee_roster set remaining_annual_leave=12,accrued_annual_leave=15 where profile_id=$1',[peer])
  await db.exec('reset role')
  await db.query(`insert into app.employee_leave_accrual(employee_id,company_id,hire_date,cycle_start,cycle_end,calculated_grant,source_key)
    select $1,$2,'2024-11-03',starts_on,ends_on,grant_days,'fixture' from app.employee_leave_cycle('2024-11-03','2026-10-29')`,[peer,company])
  const balance=async()=>{await db.exec('reset role');return Number(await value('select remaining_annual_leave from employee_roster where profile_id=$1',[peer]))}
  await actor(peer);const old=await create('annual','2026-10-30','2026-10-30',peer)
  assert.equal(await balance(),11)
  await actor(peer);const future=await create('annual','2026-11-05','2026-11-05',peer)
  assert.equal(await balance(),11,'다음 기간 예약으로 현재 잔여 차감하지 않음')
  await actor(peer);const crossing=await create('annual','2026-11-03','2026-11-04',peer)
  assert.equal(await balance(),10,'기간을 걸치는 신청은 날짜별 1일씩 분배')
  await actor(peer)
  await assert.rejects(()=>create('annual','2026-12-01','2026-12-31',peer),/다음 연차 기간/)
  await assert.rejects(()=>db.query("select app.refresh_employee_leave($1,'2026-11-04')",[peer]),/permission denied/)
  await assert.rejects(()=>db.query('select * from app.employee_leave_accrual'),/permission denied/)
  await assert.rejects(()=>db.query("update app.leave_balance_entries set allocations='{}'"),/permission denied/)
  await db.exec("reset role;select set_config('test.today','2026-11-04',false)")
  await db.query("select app.refresh_employee_leave($1,'2026-11-04')",[peer])
  assert.equal(await balance(),13,'새 발생15일에서 미리 예약한2일 차감')
  await db.query("select app.refresh_employee_leave($1,'2026-11-04')",[peer]);assert.equal(await balance(),13,'재실행으로 초기화 반복하지 않음')
  await actor(peer);await db.query("update company_leave_requests set status='cancelled' where id=$1",[old.id]);assert.equal(await balance(),13,'이전 기간 취소는 현재 잔여에 영향 없음')
  await actor(peer);await db.query("update company_leave_requests set status='cancelled' where id=$1",[crossing.id]);assert.equal(await balance(),14,'기간을 걸친 취소도 현재기간1일만 복원')
  await actor(peer);await db.query("update company_leave_requests set status='cancelled' where id=$1",[future.id]);assert.equal(await balance(),15)
  await actor(peer);await create('half','2026-11-06','2026-11-06',peer);assert.equal(await balance(),14.5)
  await actor(peer);await create('quarter','2026-11-09','2026-11-09',peer);assert.equal(await balance(),14.25)
  await db.exec("select set_config('test.today','2026-10-29',false)")
  // Separate new hire: an already included Excel month must not be granted twice.
  const fresh='10000000-0000-4000-8000-000000000005'
  await db.query("insert into profiles(id,company_id,status,display_name,hire_date) values($1,$2,'active','신입','2026-03-30')",[fresh,company])
  await actor(ops);await db.query('insert into employee_roster(profile_id,company_id,remaining_annual_leave,accrued_annual_leave) values($1,$2,3.5,7)',[fresh,company]);await db.exec('reset role')
  await db.query("insert into app.employee_leave_accrual select $1,$2,'2026-03-30',starts_on,ends_on,7,'fixture',now(),now() from app.employee_leave_cycle('2026-03-30','2026-10-29')",[fresh,company])
  await db.query("select app.refresh_employee_leave($1,'2026-10-31')",[fresh]);assert.equal(Number(await value('select remaining_annual_leave from employee_roster where profile_id=$1',[fresh])),3.5)
  await db.query("select app.refresh_employee_leave($1,'2026-12-01')",[fresh]);assert.equal(Number(await value('select remaining_annual_leave from employee_roster where profile_id=$1',[fresh])),4.5)
  await db.query("select app.refresh_employee_leave($1,'2027-03-31')",[fresh]);assert.equal(Number(await value('select remaining_annual_leave from employee_roster where profile_id=$1',[fresh])),15)
  await db.query("update profiles set hire_date='2026-03-31' where id=$1",[fresh])
  await assert.rejects(()=>db.query("select app.refresh_employee_leave($1,'2027-04-01')",[fresh]),/입사일/)
  console.log('leave-anniversary: 입사일 다음날·윤년·월별 증가·25일 상한·현재값 유지·미래 예약·기간별 차감/취소·초기화 중복 방지·직접 조작 차단 통과')
}
