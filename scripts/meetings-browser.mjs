 console.log('meetings-browser: 기존 회의록·자료·실패 입력 보존·다음 회차/종료·미리보기 쓰기 차단 + 비공개 준비/호스트 선택·안내 저장·확정·참석 가능/불가·1:1/단체 채팅 패널·일정 변경 응답 초기화 통과')
