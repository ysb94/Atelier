import assert from 'node:assert/strict'
export async function verifyMeetings(page,origin){
 await page.goto(origin+'/meetings')
 await page.getByText('회의 저장 검증',{exact:true}).waitFor()
 const row=()=>page.locator('li').filter({has:page.getByText('회의 저장 검증',{exact:true})})
 const open=async()=>{await row().getByRole('button',{name:/1차/}).click();await page.getByRole('dialog',{name:'회의 저장 검증'}).waitFor()}
 const dialog=()=>page.getByRole('dialog',{name:'회의 저장 검증'})
 await open()
 await page.getByLabel('회의 내용',{exact:true}).fill('저장 후 새로고침 검증 회의록')
 await dialog().getByRole('button',{name:'닫기',exact:true}).click()
 await dialog().waitFor({state:'hidden'})
 await page.reload();await page.getByText('회의 저장 검증',{exact:true}).waitFor();await open()
 assert.equal(await page.getByLabel('회의 내용',{exact:true}).inputValue(),'저장 후 새로고침 검증 회의록')
 await dialog().locator('input[type=file]').setInputFiles({name:'회의 자료.txt',mimeType:'text/plain',buffer:Buffer.from('공유 자료 검증')})
 await dialog().getByText('회의 자료.txt',{exact:true}).waitFor()
 const download=page.waitForEvent('download')
 await dialog().getByRole('button',{name:'회의 자료.txt 받기',exact:true}).click()
 assert.equal((await download).suggestedFilename(),'회의 자료.txt')
 await dialog().getByRole('button',{name:'닫기',exact:true}).click();await dialog().waitFor({state:'hidden'})
 await page.reload();await page.getByText('회의 저장 검증',{exact:true}).waitFor();await open()
 await dialog().getByText('회의 자료.txt',{exact:true}).waitFor()
 await dialog().getByRole('button',{name:'회의 자료.txt 삭제',exact:true}).click()
 await dialog().getByText('회의 자료.txt',{exact:true}).waitFor({state:'hidden'})
 await page.evaluate(()=>{const s=JSON.parse(sessionStorage.getItem('atelier:meeting-fixture'));s.failNext=true;sessionStorage.setItem('atelier:meeting-fixture',JSON.stringify(s))})
 await page.getByLabel('회의 내용',{exact:true}).fill('실패해도 유지할 입력')
 await dialog().getByRole('button',{name:'닫기',exact:true}).click()
 await dialog().getByRole('alert').getByText('검증용 저장 실패',{exact:false}).waitFor()
 assert.equal(await page.getByLabel('회의 내용',{exact:true}).inputValue(),'실패해도 유지할 입력')
 await dialog().getByRole('button',{name:'닫기',exact:true}).click();await dialog().waitFor({state:'hidden'})
 await open();await dialog().getByRole('button',{name:'저장하고 다음 회의 진행',exact:true}).click();await dialog().waitFor({state:'hidden'})
 await row().getByRole('button',{name:'다음 차 예정',exact:true}).waitFor()
 await page.reload();await row().getByRole('button',{name:'다음 차 예정',exact:true}).waitFor()
 const audit=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')).audit.length)
 const bar=page.getByRole('region',{name:'개발자 화면 미리보기'})
 await bar.getByRole('button',{name:'담당자',exact:true}).click()
 await row().getByRole('button',{name:/1차/}).click()
 await page.getByLabel('회의 내용',{exact:true}).fill('실제 저장 금지')
 await dialog().getByRole('button',{name:'닫기',exact:true}).click();await dialog().waitFor({state:'hidden'})
 assert.equal(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')).audit.length),audit,'화면 테스트 중 실제 쓰기 RPC 없음')
 await bar.getByRole('button',{name:'미리보기 종료',exact:true}).click()
 await open();assert.equal(await page.getByLabel('회의 내용',{exact:true}).inputValue(),'실패해도 유지할 입력')
 await dialog().getByRole('button',{name:'회의건 종료',exact:true}).click();await dialog().waitFor({state:'hidden'})
 await page.getByRole('tab',{name:'완료 1',exact:true}).waitFor()
 await page.reload();await page.getByRole('tab',{name:'완료 1',exact:true}).click();await page.getByText('회의 저장 검증',{exact:true}).waitFor()
 console.log('meetings-browser: 회의록/파일 저장 후 새로고침·다운로드/삭제·실패 입력 보존·다음 회차/종료·화면 테스트 실제 쓰기 차단 통과')
}
