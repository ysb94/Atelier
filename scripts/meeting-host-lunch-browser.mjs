import assert from 'node:assert/strict'

export async function verifyMeetingHostLunchBrowser(page,origin){
 await page.goto(origin+'/meetings')
 await page.evaluate(()=>{sessionStorage.removeItem('atelier:meeting-fixture');sessionStorage.removeItem('atelier:meeting-lunch-fixture')})
 await page.reload()
 const row=()=>page.locator('li').filter({has:page.getByText('회의 저장 검증',{exact:true})})
 const detail=()=>page.getByRole('dialog',{name:'회의 저장 검증',exact:true})
 const schedule=()=>page.getByRole('dialog',{name:'회의 일정 확정',exact:true})
 async function openSchedule(){await row().getByRole('button',{name:'상세',exact:true}).click();await detail().getByRole('button',{name:'일정 변경',exact:true}).click();await schedule().getByRole('button',{name:'소회의실 11:00 시작',exact:true}).waitFor()}
 await openSchedule()
 for(const clock of ['11:30','12:00','12:30']) assert.equal(await schedule().getByRole('button',{name:`소회의실 ${clock} 시작`,exact:true}).isEnabled(),false,clock+' 점심 겹침 차단')
 assert.equal(await schedule().getByRole('button',{name:'소회의실 11:00 시작',exact:true}).isEnabled(),true,'점심 시작에 끝나는 회의 허용')
 assert.equal(await schedule().getByRole('button',{name:'소회의실 13:00 시작',exact:true}).isEnabled(),true,'점심 종료에 시작하는 회의 허용')
 assert.equal(await schedule().getByRole('button',{name:'검증 동료 12:00 일정',exact:true}).isEnabled(),false,'멤버 시간표 우회 선택 차단')
 await schedule().getByRole('button',{name:'소회의실 11:00 시작',exact:true}).click()
 const confirmations=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')).audit.filter(name=>name==='confirm_company_meeting').length)
 await page.evaluate(()=>sessionStorage.setItem('atelier:meeting-lunch-fixture',JSON.stringify({lunch_start:'11:30:00',lunch_end:'12:30:00'})))
 await schedule().getByRole('button',{name:'일정 확정',exact:true}).click()
 await schedule().getByRole('alert').filter({hasText:'회사 점심시간 11:30–12:30과 겹칩니다'}).waitFor()
 assert.equal(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')).audit.filter(name=>name==='confirm_company_meeting').length),confirmations,'확정 직전에 변경된 점심시간 재검사')
 await schedule().getByRole('button',{name:'닫기',exact:true}).click()
 await page.reload();await openSchedule()
 assert.equal(await schedule().getByRole('button',{name:'소회의실 11:00 시작',exact:true}).isEnabled(),false,'새로고침 후 회사 점심시간 적용')
 assert.equal(await schedule().getByRole('button',{name:'소회의실 12:30 시작',exact:true}).isEnabled(),true)
 await page.screenshot({path:'.tmp/meeting-lunch-rules.png',fullPage:true})
 await schedule().getByRole('button',{name:'닫기',exact:true}).click()
 await page.evaluate(()=>sessionStorage.setItem('atelier:meeting-lunch-fixture',JSON.stringify({error:true})))
 await page.reload();await openSchedule()
 await schedule().getByRole('alert').filter({hasText:'점심시간을 불러오지 못했습니다'}).waitFor()
 assert.equal(await schedule().getByRole('button',{name:'소회의실 15:00 시작',exact:true}).isEnabled(),false,'점심 조회 실패를 빈 시간으로 처리하지 않음')
 await page.evaluate(()=>sessionStorage.removeItem('atelier:meeting-lunch-fixture'))
 await schedule().getByRole('button',{name:'다시 조회',exact:true}).click()
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(el=>el.getAttribute('aria-label')==='소회의실 15:00 시작'&&!el.disabled))
 await schedule().getByRole('button',{name:'닫기',exact:true}).click()
 const stored=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')))
 for(const suffix of ['&identity=employee','']){
  await page.goto(origin+'/meetings?meeting-member'+suffix)
  assert.equal(await row().getByRole('button',{name:'삭제',exact:true}).count(),0,'운영 권한이 있어도 비호스트 삭제 버튼 없음')
  await row().getByRole('button',{name:'상세',exact:true}).click()
  assert.equal(await detail().getByLabel('회의 내용',{exact:true}).evaluate(el=>el.readOnly),true)
  assert.equal(await detail().getByLabel('회의 결과',{exact:true}).evaluate(el=>el.readOnly),true)
  for(const label of ['저장','일정 변경','회의건 종료','저장하고 다음 회의 진행'])assert.equal(await detail().getByRole('button',{name:label,exact:true}).count(),0,label+' 비호스트 차단')
  assert.equal(await detail().getByRole('button',{name:'올리기',exact:true}).isEnabled(),true,'자료 공유 유지')
  await detail().getByRole('button',{name:'닫기',exact:true}).filter({hasText:/^닫기$/}).click();await detail().waitFor({state:'hidden'})
 }
 const after=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('atelier:meeting-fixture')))
 assert.deepEqual(after.audit,stored.audit,'비호스트가 상세를 닫아도 저장 RPC를 보내지 않음')
 console.log('meeting-host-lunch-browser: 점심 겹침·경계·멤버 표 우회·최신 설정 재검사·조회 실패/재시도·비호스트/운영자 읽기 전용·삭제 차단·자료 공유 유지 통과')
}
