import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

export async function verifyPermissionSettings(page,origin) {
  await page.goto(origin+'/settings/permissions')
  await page.getByRole('heading',{name:'권한·담당자 설정',exact:true}).waitFor()
  await page.getByRole('row',{name:/검증 직원.*업무 접수.*물류팀/}).waitFor()
  const original = await page.evaluate(()=>window.__permissionsFixture.grants())
  await page.getByLabel('지정할 직원',{exact:true}).selectOption('other-user')
  await page.getByLabel('권한 대상',{exact:true}).selectOption('dept-design')
  await page.getByRole('button',{name:'지정 내용 확인',exact:true}).click()
  await page.getByRole('region',{name:'권한 변경 확인'}).waitFor()
  assert.equal(await page.evaluate(()=>window.__permissionsFixture.audit.length),0,'확인 전 실제 쓰기 없음')
  await page.getByLabel('권한 대상',{exact:true}).selectOption('dept-logistics')
  assert.equal(await page.getByRole('region',{name:'권한 변경 확인'}).count(),0,'대상이 바뀌면 이전 확인 내용을 폐기')
  await page.getByLabel('권한 대상',{exact:true}).selectOption('dept-design')
  await page.getByRole('button',{name:'지정 내용 확인',exact:true}).click()
  await mkdir('.tmp',{recursive:true})
  await page.screenshot({path:'.tmp/permission-settings-preview.png',fullPage:true})
  await page.getByRole('button',{name:'변경 저장',exact:true}).click()
  await page.getByRole('status').getByText('지정 내역을 저장했습니다.',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>window.__permissionsFixture.audit.length),1)
  const newRow=page.getByRole('row',{name:/검증 직원.*업무 접수.*디자인팀/})
  await newRow.getByRole('button',{name:'해제 내용 확인',exact:true}).click()
  await page.getByRole('button',{name:'변경 저장',exact:true}).click()
  await newRow.waitFor({state:'hidden'})
  assert.deepEqual(await page.evaluate(()=>window.__permissionsFixture.grants()),original,'기존 지정 내역을 유지하며 선택한 권한만 해제')
  await page.getByRole('tab',{name:'직원별 권한',exact:true}).click()
  await page.getByLabel('지정할 직원',{exact:true}).selectOption('fixture-user')
  assert.equal(await page.getByRole('button',{name:'지정 내용 확인',exact:true}).isDisabled(),true,'본인 권한 변경 불가')
  assert.equal(await page.getByRole('button',{name:'해제 내용 확인',exact:true}).first().isDisabled(),true)
  await page.getByRole('tab',{name:'기능별 담당자',exact:true}).click()
  await page.getByLabel('지정할 직원',{exact:true}).selectOption('other-user')
  await page.evaluate(()=>window.__permissionsFixture.conflict())
  await page.getByRole('button',{name:'지정 내용 확인',exact:true}).click()
  await page.getByRole('button',{name:'변경 저장',exact:true}).click()
  await page.getByRole('status').getByText(/다른 관리자가 지정 내역/).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.__permissionsFixture.grants()),original,'동시 수정 충돌 시 덮어쓰기 없음')
  await page.getByRole('button',{name:'지정 내역 새로 불러오기',exact:true}).click()
  await page.getByRole('tab',{name:'근태·야근 승인자',exact:true}).click()
  await page.locator('#approver-departments-tab').waitFor()
  await page.getByRole('table',{name:'부서별 승인자 목록',exact:true}).waitFor()
  await page.goto(origin+'/settings/permissions?identity=employee')
  await page.getByRole('status').getByText('권한 지정 관리 또는 승인자 지정 권한이 필요합니다.',{exact:true}).waitFor()
  assert.equal(await page.getByLabel('지정할 직원',{exact:true}).count(),0)
  await page.goto(origin+'/settings/permissions?permissions-error')
  await page.getByRole('alert').getByText(/권한 지정 내역 조회 실패/).waitFor()
  assert.equal(await page.getByRole('button',{name:'지정 내용 확인',exact:true}).isDisabled(),true,'조회 오류를 미지정 성공 상태로 사용하지 않음')
  await page.goto(origin+'/settings/permissions?identity=partner')
  await page.getByLabel('권한 대상',{exact:true}).getByRole('option',{name:'검증 업체',exact:true}).waitFor({state:'attached'})
  assert.deepEqual(await page.getByLabel('지정할 권한',{exact:true}).locator('option').evaluateAll(options=>options.map(option=>option.value)),['partner.edit'],'업체 담당자는 업체 편집 담당자만 지정')
  assert.deepEqual(await page.getByLabel('권한 범위 종류',{exact:true}).locator('option').evaluateAll(options=>options.map(option=>option.value)),['partner'])
  assert.equal(await page.getByRole('tab',{name:'근태·야근 승인자',exact:true}).count(),0)
  await page.goto(origin+'/settings/permissions')
  await page.getByText('전체 승인·담당 업무 목록',{exact:true}).click()
  await page.getByRole('button',{name:'채팅 메시지 운영 설정',exact:true}).click()
  assert.equal(await page.getByLabel('지정할 권한',{exact:true}).inputValue(),'chat.moderate','담당자 목록 선택은 기존 지정 양식에 연결')
  assert.equal(await page.evaluate(()=>window.__permissionsFixture.audit.length),0,'기능 선택만으로 지정 내역을 쓰지 않음')
  await page.goto(origin+'/settings/permissions?permissions-legacy')
  const catalog=page.getByRole('table',{name:'승인자·기능별 담당자 설정 목록',exact:true})
  await catalog.waitFor()
  for(const label of ['월차/연차 승인자','반차 승인자','반반차 승인자','외근 승인자','재택 승인자','야근 승인자','출퇴근 정정 승인자','가입 승인·직원 계정 관리','출근시간 설정','회사 공지 작성·수정·게시','부서 공지 작성·수정·게시','채팅 메시지 운영','업체 담당자 지정'])await catalog.getByText(label,{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'채팅 메시지 운영 설정',exact:true}).isDisabled(),true,'기존 DB에서는 미연결 지정을 저장 가능한 것처럼 보이지 않음')
  assert.deepEqual(await page.evaluate(()=>window.__permissionsFixture.calls),[],'기존 모드는 미적용 권한 RPC를 호출하지 않음')
  await catalog.getByRole('row',{name:/월차\/연차 승인자/}).getByRole('button',{name:'월차/연차 승인자 설정',exact:true}).click()
  await page.getByRole('table',{name:'부서별 승인자 목록',exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>window.__permissionsFixture.audit.length),0,'기존 승인자 설정 열기만으로 쓰기 없음')
  await page.getByRole('button',{name:'전체 승인·담당 업무',exact:true}).click()
  await page.getByLabel('승인·담당 업무 검색',{exact:true}).fill('공지')
  assert.equal(await catalog.getByRole('row').count(),5,'회사/부서 공지 작성·삭제 네 항목 검색')
  console.log('permission-settings-browser: 기존 지정·해제·내역 보존·본인/동시 수정 차단·전체 승인/담당 목록·기존 DB RPC 격리·승인자 연결 통과')
}
