import assert from 'node:assert/strict'

export async function membersDepartmentScenario({page,origin}) {
  await page.goto(origin+'/__fixture/members?people&peopleView=members&organization-editor',{waitUntil:'commit'})
  const tabs=page.getByRole('group',{name:'조직·멤버 항목'})
  await tabs.waitFor({timeout:90000})
  assert.deepEqual(await tabs.getByRole('button').allTextContents(),['조직도','멤버','회사 부서'])
  const workspace=page.getByRole('region',{name:'회사 부서와 업무 파트'})
  const employeeSearch=page.getByRole('textbox',{name:'직원 검색',exact:true})
  await employeeSearch.waitFor()
  assert.equal(await workspace.count(),0)
  await tabs.getByRole('button',{name:'회사 부서',exact:true}).click()
  await page.waitForURL(url=>url.searchParams.get('peopleView')==='departments')
  await workspace.waitFor()
  assert.equal(await employeeSearch.count(),0)
  await page.getByText('화면 미리보기 · 변경사항은 새로고침하면 초기화됩니다.',{exact:true}).waitFor()
  const original=await page.evaluate(()=>JSON.stringify(window.__fixtureDepartments))
  const planning=workspace.locator('[data-department-id="fixture-bag"]')
  const md=workspace.locator('[data-department-id="fixture-md"]')
  const operations=workspace.locator('[data-department-id="fixture-operations"]')
  assert.equal(await planning.getByText('백팩',{exact:true}).isVisible(),true)
  assert.equal(await planning.getByText('어패럴',{exact:true}).isVisible(),true)
  assert.equal(await workspace.locator('[data-department-id="fixture-apparel"]').count(),0,'기획 부서는 화면에서만 하나로 묶음')
  assert.equal(await md.getByText('MD',{exact:true}).isVisible(),true)
  assert.equal(await md.getByText('AMD',{exact:true}).isVisible(),true)
  await workspace.getByRole('button',{name:'기존 부서 업무 파트 펼치기',exact:true}).waitFor()

  await planning.getByRole('button',{name:'업무 파트 추가',exact:true}).click()
  await planning.getByLabel('업무 파트 이름',{exact:true}).fill('백팩')
  await planning.getByRole('button',{name:'추가',exact:true}).click()
  await planning.getByRole('alert').getByText('같은 이름이 이미 있습니다.',{exact:true}).waitFor()
  await planning.getByLabel('업무 파트 이름',{exact:true}).fill('액세서리')
  await planning.getByRole('button',{name:'추가',exact:true}).click()
  await planning.getByRole('button',{name:'액세서리 이름 변경',exact:true}).click()
  await planning.getByLabel('업무 파트 이름',{exact:true}).fill('소품')
  await planning.getByRole('button',{name:'적용',exact:true}).click()
  await planning.getByRole('button',{name:'소품 중지',exact:true}).click()
  await planning.getByRole('button',{name:'소품 사용',exact:true}).waitFor()
  await planning.getByRole('button',{name:'소품 사용',exact:true}).click()
  await planning.getByRole('button',{name:'기획팀 업무 파트 접기',exact:true}).click()
  assert.equal(await planning.getByText('소품',{exact:true}).isVisible(),false)
  await planning.getByRole('button',{name:'기획팀 업무 파트 펼치기',exact:true}).click()
  await planning.getByText('소품',{exact:true}).waitFor()

  await operations.getByRole('button',{name:'운영지원팀 업무 파트 펼치기',exact:true}).click()
  await operations.getByText('등록된 업무 파트 없음',{exact:true}).waitFor()
  await operations.getByRole('button',{name:'업무 파트 추가',exact:true}).click()
  await operations.getByLabel('업무 파트 이름',{exact:true}).fill('인사')
  await operations.getByRole('button',{name:'추가',exact:true}).click()
  await operations.getByText('인사',{exact:true}).waitFor()

  await workspace.getByRole('button',{name:'부서 추가',exact:true}).click()
  await workspace.getByLabel('부서 이름',{exact:true}).fill('검토용 부서')
  await workspace.getByRole('button',{name:'추가',exact:true}).click()
  await workspace.getByRole('button',{name:'검토용 부서 업무 파트 접기',exact:true}).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.__fixtureDepartmentCalls),[],'모든 UI 편집에서 기존 DB 쓰기 경로를 호출하지 않음')
  assert.equal(await page.evaluate(()=>JSON.stringify(window.__fixtureDepartments)),original,'원본 부서 목록 보존')
  await page.setViewportSize({width:320,height:1000})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'모바일 가로 넘침 없음')
  await page.setViewportSize({width:1440,height:1100})
  await page.reload({waitUntil:'commit'})
  await workspace.waitFor()
  assert.equal(await workspace.getByText('소품',{exact:true}).count(),0)
  assert.equal(await workspace.getByText('인사',{exact:true}).count(),0)
  assert.equal(await workspace.getByRole('button',{name:'검토용 부서 업무 파트 접기',exact:true}).count(),0)
  assert.equal(await tabs.getByRole('button',{name:'회사 부서',exact:true}).getAttribute('aria-pressed'),'true')
  await tabs.getByRole('button',{name:'멤버',exact:true}).click()
  await employeeSearch.waitFor()
  assert.equal(await workspace.count(),0)

  const denied=await page.context().newPage(),errors=[]
  denied.on('pageerror',error=>errors.push(error.message))
  try{
    await denied.goto(origin+'/__fixture/members?people&peopleView=members&departmentId=2e49ef43-75b9-4c89-b42d-9fd50ad9087b',{waitUntil:'commit'})
    await denied.getByRole('textbox',{name:'직원 검색',exact:true}).waitFor()
    assert.equal(await denied.getByRole('button',{name:'회사 부서',exact:true}).count(),0)
    await denied.goto(origin+'/__fixture/members?people&peopleView=departments',{waitUntil:'commit'})
    await denied.locator('#root > div').waitFor({state:'attached'})
    assert.equal(await denied.getByRole('region',{name:'회사 부서와 업무 파트'}).count(),0)
    assert.deepEqual(await denied.evaluate(()=>window.__fixtureDepartmentCalls),[])
    assert.deepEqual(errors,[])
  }finally{await denied.close()}
  return {method:'offline actual component and profiles API adapter',tabOrder:true,memberListSeparate:true,planningGrouped:true,mdParts:true,localPartEditing:true,duplicatesBlocked:true,refreshResets:true,mobileFits:true,orgManagersOnly:true,sourcePreserved:true,remoteWrites:false}
}
