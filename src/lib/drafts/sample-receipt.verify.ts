import assert from 'node:assert/strict'
import { applySampleOrigin, canReceiveSample, receiveSample, registerNextReceivedSample, sampleCountry, sampleSentToChinaTeam } from './sample-receipt'
import { attachSampleWorkOrderFile, normalizeSampleWorkOrders, sampleElapsedDays, sanitizeSampleWorkOrders, setLatestSampleWorkOrderPassed, setLatestSampleWorkOrderShipped } from './sample-work-order'

const initial = attachSampleWorkOrderFile([], { url: 'data:file,first', name: 'first.xlsx' }, '2026-10-20T01:00:00Z')
assert.equal(canReceiveSample(initial[0]!, '중국'), false)
assert.throws(() => receiveSample(initial, initial[0]!.id, '중국'), /발송 상태/)
assert.equal(sampleCountry('국내 생산').code, 'KO')
assert.equal(sampleCountry('중국 OEM').code, 'CN')
const shipped = setLatestSampleWorkOrderShipped(initial, true, '2026-10-22T01:00:00Z')
const snapshot = JSON.stringify(shipped)
assert.equal(normalizeSampleWorkOrders(shipped)[0]!.receivedAt, null, '중국 발송일로 수령일을 추측하지 않음')
assert.throws(() => registerNextReceivedSample(shipped, { url: 'file', name: 'next' }, '중국', '중국'), /실물 수령/)
const received = receiveSample(shipped, shipped[0]!.id, '중국', '2026-10-23T01:00:00Z')
assert.equal(received.length, 1)
assert.equal(received[0]!.passed, false)
assert.equal(received[0]!.returnedAt, shipped[0]!.returnedAt)
assert.equal(received[0]!.shippedAt, initial[0]!.shippedAt)
assert.equal(receiveSample(received, received[0]!.id, '중국', '2026-10-28T01:00:00Z')[0]!.receivedAt, '2026-10-23T01:00:00Z', '반복 수령 확인 시 원래 날짜 유지')
assert.equal(JSON.stringify(shipped), snapshot, '기존 입력 배열을 변경하지 않음')
assert.equal(sampleElapsedDays(received[0]!.receivedAt!, new Date('2026-10-28T01:00:00Z')), 5)
assert.throws(() => registerNextReceivedSample(received, { url: '', name: '' }, '중국', '중국'), /파일/)
const next = registerNextReceivedSample(received, { url: 'data:file,second', name: 'second.xlsx' }, '한국', '중국', '2026-10-28T01:00:00Z')
assert.equal(next.length, 2)
assert.equal(next[1]!.round, 2)
assert.deepEqual(next[0], received[0], '이전 파일·등록일·발송일·수령일 유지')
assert.equal(next[1]!.returnedAt, null)
assert.equal(next[1]!.receivedAt ?? null, null)
assert.equal(next[1]!.shipped, false)
assert.equal(next[1]!.originCountry, '한국')
assert.equal(next[0]!.originCountry, '중국', '차수별 국가 유지')
assert.equal(registerNextReceivedSample([...received,{...initial[0]!,id:'pending',round:2,url:null}],{url:'file',name:'next'},'한국','중국')[1]!.round,2, '비어 있는 임시 차수가 등록 차수를 건너뛰지 않음')
assert.throws(() => receiveSample(next, next[0]!.id, '한국'), /현재 진행/)
assert.equal(canReceiveSample(next[1]!, '한국'), true, '국내 샘플에 중국팀 발송을 요구하지 않음')
const domestic = receiveSample(next, next[1]!.id, '한국', '2026-10-29T01:00:00Z')
const approved = setLatestSampleWorkOrderPassed(domestic, true, '2026-10-30T01:00:00Z')
const restored = normalizeSampleWorkOrders(JSON.parse(JSON.stringify(sanitizeSampleWorkOrders(approved))))
assert.equal(restored[0]!.receivedAt, received[0]!.receivedAt)
assert.equal(restored[1]!.receivedAt, domestic[1]!.receivedAt)
assert.equal(restored[1]!.passed, true, '국내 샘플의 수령 후 합격·저장·재조회 유지')
assert.equal(restored[1]!.shipped, false, '국내 수령을 중국 발송으로 기록하지 않음')
assert.throws(() => registerNextReceivedSample(restored,{url:'file',name:'next'},'한국','한국'), /실물 수령/)
assert.equal(sampleSentToChinaTeam(undefined, ''), true, '제조국이 없으면 기존처럼 중국팀 목록에 둔다')
assert.equal(sampleSentToChinaTeam(undefined, '한국'), false, '기획안 제조국이 한국이면 전달하지 않는다')
assert.equal(sampleSentToChinaTeam('중국', '한국'), true, '차수 국가가 중국이면 전달한다')
assert.equal(sampleSentToChinaTeam('한국', '중국'), false, '차수 국가가 한국이면 기록만 남긴다')
const recorded = applySampleOrigin(initial, '한국')
assert.equal(recorded[0]?.originCountry, '한국')
assert.equal(recorded[0]?.assigneeName, '')
assert.equal(applySampleOrigin(setLatestSampleWorkOrderShipped(applySampleOrigin(initial, '중국'), true), '한국')[0]?.originCountry, '중국', '중국 발송 뒤에는 한국으로 되돌리지 않는다')
console.log('sample-receipt: 등록·발송·수령 분리, 수령 반복, 새 차수 실등록, 과거 이력, 국내 샘플, 저장·재조회 검증 통과')
